import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { scenario, assert, until, closeApp } from './context.mjs';

await scenario('home-workflows', async c => {
  c.seed({ projectRoot: c.dir });
  const geometry = c.copy('cad/examples/STP/block.stp');
  let app = await c.launch(); let home = await c.page(app, 'home');
  const errors = []; home.on('pageerror', error => errors.push(error.message));
  await home.locator('#study-create:enabled').waitFor();
  await home.locator('#study-create').click();
  let form = home.locator('#workflow-form');
  await form.locator('[type=submit]').click();
  assert.match(await home.locator('#workflow-form-error').textContent(), /Enter a value/);
  await home.locator('#workflow-input-source').fill(path.join(c.dir, 'missing.step'));
  await home.locator('#workflow-input-name').fill('Baseline');
  await form.locator('[type=submit]').click();
  await until(async () => /ENOENT|no such file/i.test(await home.locator('#workflow-form-error').textContent()), 'backend error retained');
  assert.equal(await home.locator('#workflow-input-name').inputValue(), 'Baseline');
  await home.locator('#workflow-input-source').fill(geometry);
  await form.locator('[type=submit]').click();
  await form.waitFor({ state: 'hidden' });
  const projectFile = path.join(c.dir, '.kkss/project.json');
  const project = () => JSON.parse(fs.readFileSync(projectFile, 'utf8'));
  assert.equal(project().studies.length, 1);
  await home.locator('#study-plan-sweep').click();
  await home.locator('#workflow-input-parameterPath').fill('values.problem.timeStep');
  await home.locator('#workflow-input-values').fill('bad JSON');
  await form.locator('[type=submit]').click();
  assert.match(await home.locator('#workflow-form-error').textContent(), /valid JSON array/);
  await home.locator('#workflow-input-values').fill('[]');
  await form.locator('[type=submit]').click();
  assert.match(await home.locator('#workflow-form-error').textContent(), /1–50/);
  await home.keyboard.press('Escape');
  assert.equal(await home.locator('#study-plan-sweep').evaluate(el => document.activeElement === el), true);
  assert.equal(project().studies.length, 1);
  await home.locator('#study-plan-sweep').click();
  await home.locator('#workflow-input-parameterPath').fill('values.problem.timeStep');
  await home.locator('#workflow-input-values').fill('[0.05, 0.1]');
  // Same-tick repeat submission must not create two previews or enqueue twice.
  await form.evaluate(el => { el.requestSubmit(); el.requestSubmit(); });
  await form.getByRole('button', { name: 'Persist paused plan', exact: true }).waitFor();
  assert.equal(project().studies.length, 1, 'preview does not create variants');
  await form.getByRole('button', { name: 'Persist paused plan', exact: true }).click();
  await form.getByRole('button', { name: 'Start plan', exact: true }).waitFor();
  assert.equal(project().studies.length, 3);
  assert.equal(project().queue.paused, true);
  assert.equal(project().queue.tasks.every(task => task.state === 'waiting'), true);
  await form.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(project().queue.paused, true, 'dismissing start preserves the paused plan');
  assert.deepEqual(errors, []);
  await closeApp(app);

  // A real local result and recorded run; no Python or solver installation needed.
  const p = project(); p.queue = { paused: true, tasks: [] };
  const study = p.studies[0]; p.activeStudyId = study.id; p.activeRunId = 'fixture-run';
  const directory = '.kkss/runs/fixture-run'; fs.mkdirSync(path.join(c.dir, directory), { recursive: true });
  const resultPath = `${directory}/result.vtk`;
  const vtk = '# vtk DataFile Version 3.0\nQuantity\nASCII\nDATASET UNSTRUCTURED_GRID\nPOINTS 4 float\n0 0 0 1 0 0 0 1 0 0 0 1\nCELLS 1 5\n4 0 1 2 3\nCELL_TYPES 1\n10\nPOINT_DATA 4\nSCALARS TEMPERATURE float 1\nLOOKUP_TABLE default\n1 2 3 4\n';
  fs.writeFileSync(path.join(c.dir, resultPath), vtk);
  study.runs = [{ id: 'fixture-run', studyId: study.id, sourceRevision: study.source.revision, meshRevision: 'fixture', settings: study.caseSettings, directory, state: 'succeeded', artifacts: [{ role: 'result', ownerId: 'fixture-run', reference: { kind: 'project', path: resultPath, revision: createHash('sha256').update(vtk).digest('hex') } }] }];
  fs.writeFileSync(projectFile, JSON.stringify(p));
  app = await c.launch(); home = await c.page(app, 'home'); form = home.locator('#workflow-form');
  await home.locator('#study-evaluate-quantity:enabled').waitFor();
  await home.locator('#study-evaluate-quantity').click();
  await home.locator('#workflow-input-field').fill('TEMPERATURE');
  await home.locator('#workflow-input-component').selectOption('scalar');
  await home.locator('#workflow-input-unit').fill('K');
  const fieldBoxes = await form.locator('.workflow-form-field').evaluateAll(labels => labels.map(label => {
    const caption = label.querySelector('span').getBoundingClientRect(); const input = label.querySelector('input,select,textarea').getBoundingClientRect();
    return { captionBottom: caption.bottom, inputTop: input.top, inputHeight: input.height };
  }));
  assert.ok(fieldBoxes.every(box => box.captionBottom <= box.inputTop && box.inputHeight >= 20), 'labels and controls do not overlap');
  await home.screenshot({ path: '/tmp/kkss-home-quantity.png' });
  await app.evaluate(({ BaseWindow }) => { const window = BaseWindow.getAllWindows()[0]; window.setMinimumSize(600, 500); window.setSize(720, 760); });
  await until(async () => await home.evaluate(() => innerWidth < 820), 'narrow Home layout');
  assert.equal(await home.locator('#home').evaluate(el => el.scrollWidth <= el.clientWidth), true, 'narrow form has no horizontal overflow');
  await home.locator('#workflow-input-timeStep').fill('-1');
  await form.locator('[type=submit]').click();
  assert.match(await home.locator('#workflow-form-error').textContent(), /non-negative integer/);
  await home.locator('#workflow-input-timeStep').fill('');
  await form.locator('[type=submit]').click();
  await until(async () => await form.isHidden() || !!(await home.locator('#workflow-form-error').textContent()), 'quantity result', 120000);
  assert.equal(await home.locator('#workflow-form-error').textContent(), '');
  const saved = project().studies[0].runs[0];
  assert.ok(saved.evidence, 'quantity evaluation persists evidence');
  assert.match(await home.locator('#run-review').textContent(), /"value": 4/);
});
